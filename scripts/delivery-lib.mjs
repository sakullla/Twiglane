const SKIP_DIR = new Set(["autogenerated", "gen", "node_modules", "target"]);

export function p95(values) {
  if (!Array.isArray(values) || values.length === 0) return null;
  const sorted = values.map(Number);
  if (sorted.some((value) => !Number.isFinite(value))) return null;
  sorted.sort((left, right) => left - right);
  const index = Math.min(sorted.length - 1, Math.ceil(sorted.length * 0.95) - 1);
  return sorted[Math.max(0, index)];
}

function walk(root, relative, lines) {
  const absolute = path.join(root, relative);
  if (!existsSync(absolute)) return;
  const stat = statSync(absolute);
  if (stat.isDirectory()) {
    if (SKIP_DIR.has(path.basename(absolute))) return;
    for (const name of readdirSync(absolute)) {
      if (name === ".DS_Store") continue;
      walk(root, path.join(relative, name), lines);
    }
    return;
  }
  if (!stat.isFile()) return;
  const hash = createHash("sha256").update(readFileSync(absolute)).digest("hex");
  lines.push(`${relative.split(path.sep).join("/")}\0${hash}`);
}

export function sourceFingerprint(root) {
  const lines = [];
  for (const relative of FINGERPRINT_ROOTS) walk(root, relative, lines);
  lines.sort();
  return createHash("sha256").update(lines.join("\n")).digest("hex");
}

export function sha256File(file) {
  return createHash("sha256").update(readFileSync(file)).digest("hex");
}

export function directoryBytes(dir) {
  let total = 0;
  const stack = [dir];
  while (stack.length) {
    const current = stack.pop();
    for (const name of readdirSync(current)) {
      const absolute = path.join(current, name);
      const stat = statSync(absolute);
      if (stat.isDirectory()) stack.push(absolute);
      else if (stat.isFile()) total += stat.size;
    }
  }
  return total;
}

function finiteSamples(values, minimum) {
  return Array.isArray(values) && values.length >= minimum && values.every((value) => Number.isFinite(value) && value >= 0);
}

function prerequisiteOk(block) {
  const pre = block?.prerequisite;
  if (!pre || pre.release !== true || pre.ssd !== true || pre.acPower !== true) return false;
  if (!(Number(pre.memoryBytes) >= BUDGETS.referenceMemoryBytes)) return false;
  if (pre.diskColdStart === true) return false;
  return true;
}

function platformBlock(evidence, name) {
  return evidence?.platforms?.[name] ?? null;
}

function requirePlatforms(evidence, reasons) {
  const darwin = platformBlock(evidence, "darwin");
  const win32 = platformBlock(evidence, "win32");
  if (!darwin) reasons.push("缺少 macOS 样本");
  if (!win32) reasons.push("缺少 Windows 样本");
  return { darwin, win32 };
}

function validatePerf(id, evidence) {
  const reasons = [];
  const { darwin, win32 } = requirePlatforms(evidence, reasons);
  for (const block of [darwin, win32]) {
    if (!block) continue;
    if (!prerequisiteOk(block)) reasons.push("测量前提不足，或被标成磁盘冷启动");
    if (block.contentOk !== true) reasons.push("内容正确性未通过");
    if (typeof block.method !== "string" || !block.method.startsWith("gui")) reasons.push("不是界面测量");
    if (block.browserMock === true) reasons.push("浏览器 mock 不能代替");
  }
  const metric = (block) => {
    if (!block) return;
    if (id === "perf.startup.s") {
      if (!finiteSamples(block.firstMs, 1) || Math.max(...block.firstMs) > BUDGETS.startupFirstMs) reasons.push("首次启动超预算或样本不足");
      if (!finiteSamples(block.laterMs, 4) || p95(block.laterMs) > BUDGETS.startupLaterP95Ms) reasons.push("后续启动超预算或样本不足");
    } else if (id.startsWith("perf.status.")) {
      const size = id.endsWith(".s") ? "S" : id.endsWith(".m") ? "M" : "L";
      if (!finiteSamples(block.samplesMs, 30) || p95(block.samplesMs) > BUDGETS.statusP95Ms[size]) reasons.push(`${size} 状态超预算或样本不足`);
    } else if (id === "perf.diff.cached") {
      if (!finiteSamples(block.samplesMs, 30) || p95(block.samplesMs) > BUDGETS.diffCachedP95Ms) reasons.push("已缓存差异超预算或样本不足");
    } else if (id === "perf.diff.uncached") {
      if (!finiteSamples(block.samplesMs, 30) || p95(block.samplesMs) > BUDGETS.diffUncachedP95Ms) reasons.push("未缓存差异超预算或样本不足");
    } else if (id === "perf.diff.large") {
      if (!finiteSamples(block.samplesMs, 30) || p95(block.samplesMs) > BUDGETS.largeSummaryP95Ms) reasons.push("大文件摘要超预算或样本不足");
      if (block.truncated !== true) reasons.push("大文件没有以摘要展示");
    } else if (id === "perf.feedback") {
      if (!finiteSamples(block.samplesMs, 30) || p95(block.samplesMs) > BUDGETS.feedbackP95Ms) reasons.push("反馈超预算或样本不足");
      const tasks = Array.isArray(block.tasks) ? block.tasks : [];
      if (!["clone", "sync", "commit"].every((task) => tasks.includes(task))) reasons.push("反馈没有启动克隆、同步或提交");
    } else if (id === "perf.scroll.m") {
      if (!finiteSamples(block.frameMs, 30) || p95(block.frameMs) > BUDGETS.scrollFrameP95Ms) reasons.push("滚动帧超预算或样本不足");
    } else if (id === "perf.interact.l") {
      if (block.keyboard !== true || block.cancelled !== true || block.switched !== true) reasons.push("加载 L 时键盘、取消或仓库切换不可用");
      if (block.readStarted !== true) reasons.push("取消或切换时 L 的读取尚未开始");
    } else if (id === "perf.memory.s") {
      if (!(Number(block.privateBytes) <= BUDGETS.idlePrivateBytes)) reasons.push("空闲内存超预算");
      if (block.metric !== "phys_footprint" && block.metric !== "private-working-set") reasons.push("内存口径不是该平台的私有内存");
    } else if (id === "perf.cpu.s") {
      if (!(Number(block.cpuPercent) <= BUDGETS.idleCpuPercent)) reasons.push("空闲 CPU 超预算");
    } else if (id === "perf.git-idle") {
      if (block.lingeringGit !== false) reasons.push("空闲时仍有 Git 子进程");
    } else if (id === "perf.stability") {
      if (!(Number(block.growth) <= BUDGETS.stabilityGrowth)) reasons.push("长时内存增长超预算");
      if (block.fileSwitches !== 100 || block.repoSwitches !== 20) reasons.push("长时脚本次数不足");
      if (block.lingeringProcesses !== false) reasons.push("结束后仍有残留进程");
    }
  };
  metric(darwin);
  metric(win32);
  return reasons;
}

function validateNative(evidence) {
  const reasons = [];
  for (const name of ["darwin", "win32"]) {
    const block = platformBlock(evidence, name);
    if (!block) {
      reasons.push(`缺少 ${name} 的原生 Git 对照`);
      continue;
    }
    if (block.method !== "git-cli") reasons.push("原生 Git 对照口径不对");
    for (const size of ["S", "M", "L"]) {
      if (!finiteSamples(block.samplesMs?.[size], 30)) reasons.push(`${name} ${size} 原生 Git 样本不足`);
    }
  }
  return reasons;
}

function artifactOk(root, evidence, { directory = false } = {}) {
  const reasons = [];
  if (evidence?.productName !== "Twiglane") reasons.push("安装显示名不是 Twiglane");
  if (typeof evidence?.path !== "string" || typeof evidence?.sha256 !== "string") {
    reasons.push("缺少产物路径或摘要");
    return reasons;
  }
  const absolute = path.resolve(root, evidence.path);
  if (!existsSync(absolute)) {
    reasons.push("产物不在当前工作区");
    return reasons;
  }
  const stat = statSync(absolute);
  if (directory) {
    if (!stat.isDirectory()) reasons.push("应用目录不是目录");
    else if (directoryBytes(absolute) > BUDGETS.installDirBytes) reasons.push("安装目录超预算");
    const plist = path.join(absolute, "Contents", "Info.plist");
    if (!existsSync(plist) || sha256File(plist) !== evidence.sha256) reasons.push("应用摘要与构建不一致");
  } else if (!stat.isFile()) {
    reasons.push("安装包不是文件");
  } else {
    if (sha256File(absolute) !== evidence.sha256) reasons.push("安装包摘要与构建不一致");
    if (stat.size > BUDGETS.installerBytes) reasons.push("安装包超预算");
  }
  return reasons;
}

function readText(root, relative) {
  const file = path.join(root, relative);
  return existsSync(file) ? readFileSync(file, "utf8") : "";
}

function validateStatic(id, root, evidence) {
  const reasons = [];
  if (id === "package.webview2-cost") {
    const config = readText(root, "src-tauri/tauri.conf.json");
    const readme = readText(root, "README.md");
    const chinese = readText(root, "src-tauri/windows/SimpChinese.nsh");
    if (!config.includes("downloadBootstrapper")) reasons.push("没有配置另行下载 WebView2");
    if (!readme.includes("不计入") || !chinese.includes("不计入")) reasons.push("下载成本没有单列");
    if (evidence?.includedInInstaller !== false || evidence?.mode !== "downloadBootstrapper") reasons.push("记录把 runtime 算进了安装包");
    if (evidence?.measuredDownloadBytes !== null) reasons.push("未实测的下载字节不能写成实测值");
  } else if (id === "package.git-explained") {
    const labels = readText(root, "src/lib/labels.ts");
    const readme = readText(root, "README.md");
    if (!labels.includes("不包含 Git") || !labels.includes("WebView2") || !readme.includes("不捆绑 Git")) reasons.push("Git 或 WebView2 缺失说明不完整");
  } else if (id === "docs.support") {
    const readme = readText(root, "README.md");
    for (const heading of ["## 支持范围", "## 安装与运行", "## 恢复边界", "## 性能口径", "## 已知限制"]) {
      if (!readme.includes(heading)) reasons.push(`缺少 ${heading}`);
    }
    if (!readme.includes("研发平台") || !readme.includes("AI 聊天")) reasons.push("没有写明首版排除项");
  } else if (id === "package.signature") {
    if (evidence?.notarized !== false || evidence?.trustedDistribution !== false) reasons.push("不能把测试包写成已公证或可信发布");
    if (typeof evidence?.codesign !== "string" || evidence.codesign.trim().length < 20) reasons.push("没有 codesign 原文");
    const summary = `${evidence?.statement ?? ""}`;
    if (summary.includes("已公证") || summary.includes("已签名公开发布")) reasons.push("签名陈述与证据不符");
  }
  return reasons;
}

function validateAccept(id, evidence) {
  const reasons = [];
  const expected = id === "accept.macos" ? "darwin" : "win32";
  if (evidence?.hostPlatform !== expected) reasons.push("验收记录上的系统与目标不一致");
  if (evidence?.browserMock === true || evidence?.method === "browser-mock") reasons.push("浏览器 mock 不能代替安装包");
  if (typeof evidence?.method !== "string" || !evidence.method.startsWith("installed-app")) reasons.push("不是安装包里的界面操作");
  const oids = Array.isArray(evidence?.oids) ? evidence.oids : [];
  if (!oids.every((oid) => /^[0-9a-f]{7,64}$/.test(oid)) || oids.length < 2) reasons.push("缺少真实 Git OID");
  if (evidence?.partialCommit !== true || evidence?.pushed !== true || typeof evidence?.mergeOid !== "string") reasons.push("克隆到部分提交、推送或合并没有完成");
  if (!Array.isArray(evidence?.themes) || !evidence.themes.includes("light") || !evidence.themes.includes("dark")) {
    reasons.push("双主题验收不足");
  }
  const before = evidence?.selectionBefore;
  const moved = evidence?.selectionMoved;
  const after = evidence?.selectionAfter;
  if (
    evidence?.keyboard !== true ||
    evidence?.shortcutFocused !== true ||
    evidence?.selectionChanged !== true ||
    typeof before !== "string" ||
    typeof moved !== "string" ||
    typeof after !== "string" ||
    !moved ||
    !after ||
    moved === before ||
    after === moved
  ) {
    reasons.push("键盘没有用快捷键聚焦或用方向键改变选择");
  }
  return reasons;
}

function validateProtocol(evidence) {
  const reasons = [];
  if (evidence?.success !== true || evidence?.authFailure !== true) reasons.push("缺少成功访问或认证失败");
  if (evidence?.redacted !== true) reasons.push("没有确认日志脱敏");
  if (evidence?.localBare === true) reasons.push("本地 bare remote 不能代替协议");
  if (typeof evidence?.transcript !== "string" || evidence.transcript.length < 20) reasons.push("缺少协议记录");
  if (/:\/\/[^/\s]*:[^@\s]+@/.test(evidence?.transcript ?? "")) reasons.push("记录里仍有凭据");
  return reasons;
}

export function validateCheck(check, { root, hostPlatform }) {
  const reasons = [];
  if (!check || typeof check.id !== "string") return ["检查项缺失"];
  if (typeof check.summary !== "string" || !check.summary.trim()) reasons.push("缺少摘要");
  if (!["pass", "fail", "gap", "not_run"].includes(check.status)) reasons.push("状态无效");
  if ((check.status === "gap" || check.status === "not_run") && (typeof check.nextStep !== "string" || check.nextStep.trim().length < 8)) {
    reasons.push("缺口没有唯一下一步");
  }
  if (check.status !== "pass") return reasons;
  const evidence = check.evidence ?? {};
  if (check.id.startsWith("perf.") && check.id !== "perf.native-git") reasons.push(...validatePerf(check.id, evidence));
  if (check.id === "perf.native-git") reasons.push(...validateNative(evidence));
  if (check.id === "package.macos.app") reasons.push(...artifactOk(root, evidence, { directory: true }));
  if (check.id === "package.macos.dmg" || check.id === "package.windows.nsis") reasons.push(...artifactOk(root, evidence));
  if (check.id === "package.windows.nsis" && evidence.runtimeVerified === true && evidence.hostPlatform !== "win32") {
    reasons.push("交叉编译不能写成 Windows 运行结果");
  }
  if (["package.signature", "package.webview2-cost", "package.git-explained", "docs.support"].includes(check.id)) {
    reasons.push(...validateStatic(check.id, root, evidence));
  }
  if (check.id === "accept.macos" || check.id === "accept.windows") reasons.push(...validateAccept(check.id, evidence));
  if (check.id === "protocol.https" || check.id === "protocol.ssh") reasons.push(...validateProtocol(evidence));
  return reasons;
}

export function judgeReport(root, report, fingerprint, hostPlatform = process.platform) {
  const failures = [];
  if (!report || report.format !== "twiglane-delivery-verification/v1") failures.push("报告格式不对");
  if (report?.sourceFingerprint !== fingerprint) failures.push("构建指纹与当前源码不一致");
  const checks = new Map((report?.checks ?? []).map((check) => [check.id, check]));
  for (const id of REQUIRED_CHECKS) {
    const check = checks.get(id);
    if (!check) {
      failures.push(`${id} 缺记录`);
      continue;
    }
    const reasons = validateCheck(check, { root, hostPlatform });
    if (reasons.length) failures.push(`${id}: ${reasons.join("；")}`);
    else if (check.status !== "pass") failures.push(`${id} 为 ${check.status}`);
  }
  return {
    ok: failures.length === 0,
    summary: failures.length === 0 ? "交付记录与当前构建一致并通过预算" : failures.join(" | "),
    failures,
  };
}

export function verifyDelivery(root, hostPlatform = process.platform) {
  const reportPath = path.join(root, "docs/verification/report.json");
  if (!existsSync(reportPath)) {
    return { ok: false, summary: "缺少 docs/verification/report.json", failures: ["missing-report"] };
  }
  let report;
  try {
    report = JSON.parse(readFileSync(reportPath, "utf8"));
  } catch {
    return { ok: false, summary: "docs/verification/report.json 不是合法 JSON", failures: ["invalid-json"] };
  }
  return judgeReport(root, report, sourceFingerprint(root), hostPlatform);
}
